# This script asks for attendee name and ticket choice, then prints a personalized message on the ticket to attend a small business winter-themed pop up event in the city of Boston, MA

name = input("Please enter your name as you'd like reflected on your ticket: ")
ticket_price = float(input("Please enter 3 to purchase a standard ticket ($3). Please enter 5 to purchase a ticket including our signature brand hot chocolate served upon check in ($5)): $"))

if ticket_price == 3:
  print("Welcome " + name +"! We thank you for supporting our small business. Your standard ticket of $" + str(ticket_price) + " doesn't include a hot chocolate, but please ask a staff member if you'd like to purchase.")
elif ticket_price == 5:
  print("Welcome " + name +"! We thank you for supporting our small business. Your ticket of $" + str(ticket_price) + " includes a serving of our signature brand hot chocolate curated for you to enjoy. The product will be available for sale at the desk after the event.")
else:
  print("Please enter only 3 or 5.")

